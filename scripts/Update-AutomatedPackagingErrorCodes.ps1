<#
.SYNOPSIS
    Copies the AppVentiX Automated Packaging error-code register into this docs site.

.DESCRIPTION
    The product generates docs/reference/error-codes.md from its own code (ApCodes.cs),
    and a product test fails when the file and the code differ. This script reads that
    generated file from a product checkout, read-only, and writes
    docs/AutomatedPackaging/error-codes.md. Never edit the page by hand: change ApCodes.cs
    in the product, regenerate the register there, then run this script again.

    The script refuses, and writes nothing, when the register is missing, has changes that
    are not committed in the product checkout, or no longer has the shape it expects.

.PARAMETER ProductRepo
    The product checkout. Defaults to ..\..\AutomatedPackaging, relative to the root of this
    repository.

.EXAMPLE
    .\scripts\Update-AutomatedPackagingErrorCodes.ps1
    .\scripts\Update-AutomatedPackagingErrorCodes.ps1 -ProductRepo D:\src\AutomatedPackaging
#>
[CmdletBinding()]
param(
    [string]$ProductRepo = (Join-Path $PSScriptRoot '..\..\..\AutomatedPackaging')
)

$ErrorActionPreference = 'Stop'

$ProductRepo = (Resolve-Path -LiteralPath $ProductRepo).Path
$relative = 'docs/reference/error-codes.md'
$source = Join-Path $ProductRepo $relative
if (-not (Test-Path -LiteralPath $source -PathType Leaf)) {
    throw "No register at $source. Pass -ProductRepo with the product checkout."
}

$dirty = git -C $ProductRepo status --porcelain -- $relative
if ($LASTEXITCODE -ne 0) { throw "git status failed in $ProductRepo." }
if ($dirty) {
    throw "$relative has changes that are not committed in $ProductRepo. Commit them there first."
}
$commit = git -C $ProductRepo log -1 --format=%h -- $relative
$date = git -C $ProductRepo log -1 --format=%cs -- $relative
if ($LASTEXITCODE -ne 0 -or -not $commit) { throw "Cannot read the commit of $relative in $ProductRepo." }

$text = [IO.File]::ReadAllText($source, [Text.Encoding]::UTF8) -replace "`r`n", "`n"
$lines = $text -split "`n"

if ($lines[0] -ne '# Error code register') {
    throw "The register no longer starts with '# Error code register'. Check its shape before you copy it."
}
$summary = @(for ($i = 0; $i -lt $lines.Count; $i++) { if ($lines[$i] -eq '## Summary') { $i } })
if ($summary.Count -ne 1) {
    throw "Expected one '## Summary' heading in the register, found $($summary.Count)."
}
$body = ($lines[$summary[0]..($lines.Count - 1)] -join "`n").TrimEnd() + "`n"
if ($body -notmatch '(?m)^### `AP-[A-Z]{2}-\d{3}`') {
    throw 'The register has no code headings. Check its shape before you copy it.'
}

$header = @"
# Error codes

<!-- Generated by scripts/Update-AutomatedPackagingErrorCodes.ps1 from $relative
     of the product repository, commit $commit. Do not edit this page by hand. -->

This page lists every ``AP-`` error code of AppVentiX Automated Packaging, with its cause and what to do. The product generates this list from its own code. [Troubleshooting](troubleshooting.md#common-error-codes) has the short list of common codes.

A code never gets a different meaning. A code that is no longer used stays in the list, marked retired.

*Copied from the product's error-code register of $date (commit $commit).*


"@ -replace "`r`n", "`n"

$target = Join-Path $PSScriptRoot '..\docs\AutomatedPackaging\error-codes.md'
[IO.File]::WriteAllText($target, $header + $body, [Text.UTF8Encoding]::new($false))
$count = ([regex]::Matches($body, '(?m)^### `AP-')).Count
Write-Host "Wrote $count codes to docs/AutomatedPackaging/error-codes.md from commit $commit." -ForegroundColor Green
