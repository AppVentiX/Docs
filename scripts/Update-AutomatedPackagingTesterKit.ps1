<#
.SYNOPSIS
    Copies the AppVentiX Automated Packaging tester kit into this docs site.

.DESCRIPTION
    The product keeps the tester kit in tester-kit/ (its CH-549). This script reads that folder
    from a product checkout, read-only, and writes two things:

    - docs/AutomatedPackaging/downloads/automated-packaging-tester-kit.zip, the folder as
      committed (git archive), for AI tools that can write files;
    - docs/AutomatedPackaging/tester-kit-instructions.md, AGENTS.md followed by questions.md,
      for a chat AI that a tester gives the page's link to.

    Never edit either by hand: change tester-kit/ in the product, commit it there, then run this
    script again. The script refuses, and writes nothing, when tester-kit/ is missing or has
    changes that are not committed.

.PARAMETER ProductRepo
    The product checkout. Defaults to ..\..\..\AutomatedPackaging, relative to this script.

.EXAMPLE
    .\scripts\Update-AutomatedPackagingTesterKit.ps1
#>
[CmdletBinding()]
param(
    [string]$ProductRepo = (Join-Path $PSScriptRoot '..\..\..\AutomatedPackaging')
)

$ErrorActionPreference = 'Stop'

$ProductRepo = (Resolve-Path -LiteralPath $ProductRepo).Path
$kit = Join-Path $ProductRepo 'tester-kit'
foreach ($name in 'AGENTS.md', 'questions.md', 'README.md') {
    if (-not (Test-Path -LiteralPath (Join-Path $kit $name) -PathType Leaf)) {
        throw "No tester-kit/$name in $ProductRepo. Pass -ProductRepo with the product checkout."
    }
}

$dirty = git -C $ProductRepo status --porcelain -- tester-kit
if ($LASTEXITCODE -ne 0) { throw "git status failed in $ProductRepo." }
if ($dirty) { throw "tester-kit/ has changes that are not committed in $ProductRepo. Commit them there first." }
$commit = git -C $ProductRepo log -1 --format=%h -- tester-kit
$date = git -C $ProductRepo log -1 --format=%cs -- tester-kit
if ($LASTEXITCODE -ne 0 -or -not $commit) { throw "Cannot read the commit of tester-kit/ in $ProductRepo." }

$section = Join-Path $PSScriptRoot '..\docs\AutomatedPackaging'

# The download: the folder exactly as committed.
$downloads = Join-Path $section 'downloads'
New-Item -ItemType Directory -Force -Path $downloads | Out-Null
$zip = Join-Path $downloads 'automated-packaging-tester-kit.zip'
git -C $ProductRepo archive --format=zip -o $zip $commit tester-kit
if ($LASTEXITCODE -ne 0) { throw "git archive failed in $ProductRepo." }

# The page: the instructions, then the questions one heading level down.
function Read-Committed([string]$name) {
    $text = git -C $ProductRepo show "${commit}:tester-kit/$name"
    if ($LASTEXITCODE -ne 0) { throw "Cannot read tester-kit/$name at $commit." }
    ($text -join "`n").TrimEnd() + "`n"
}
$agents = Read-Committed 'AGENTS.md'
$questions = Read-Committed 'questions.md'
if ($agents -notmatch '^# ') { throw 'AGENTS.md no longer starts with a level-1 heading. Check its shape.' }
if ($questions -notmatch '^# ') { throw 'questions.md no longer starts with a level-1 heading. Check its shape.' }

# Outside code blocks only: AGENTS.md holds templates with headings in them.
$inFence = $false
$questions = (($questions -split "`n") | ForEach-Object {
    if ($_ -match '^```') { $inFence = -not $inFence }
    if (-not $inFence -and $_ -match '^#') { '#' + $_ } else { $_ }
}) -join "`n"

$header = @"
---
title: Instructions for the AI
---

<!-- Generated by scripts/Update-AutomatedPackagingTesterKit.ps1 from tester-kit/ of the
     product repository, commit $commit. Do not edit this page by hand. -->

!!! note "For the tester"
    Give the link to this page to your AI, with this message: *Read this page and follow the
    instructions on it. Start a findings session.* See [Report findings with an AI](tester-kit.md).

*Copied from the product's tester kit of $date (commit $commit).*


"@ -replace "`r`n", "`n"

$page = Join-Path $section 'tester-kit-instructions.md'
[IO.File]::WriteAllText($page, $header + $agents + "`n" + $questions, [Text.UTF8Encoding]::new($false))
Write-Host "Wrote the tester kit zip and tester-kit-instructions.md from commit $commit." -ForegroundColor Green
